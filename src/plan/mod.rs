//! Refactor plan generation

use crate::patterns::{Finding, PatternType};
use chrono::Utc;

/// A generated refactor plan for a finding
#[derive(Debug, Clone)]
pub struct RefactorPlan {
    pub finding: Finding,
    pub generated_at: String,
    pub markdown: String,
}

impl RefactorPlan {
    /// Generate a refactor plan for a finding
    pub fn generate(finding: &Finding) -> Self {
        let generated_at = Utc::now().format("%Y-%m-%dT%H:%M:%SZ").to_string();
        let markdown = generate_markdown(finding, &generated_at);

        Self {
            finding: finding.clone(),
            generated_at,
            markdown,
        }
    }

    /// Write plan to a file
    pub fn write_to_file(&self, path: &std::path::Path) -> std::io::Result<()> {
        std::fs::write(path, &self.markdown)
    }

    /// Get plan as markdown string
    pub fn as_markdown(&self) -> &str {
        &self.markdown
    }
}

fn generate_markdown(finding: &Finding, generated_at: &str) -> String {
    let mut md = String::new();

    // Header
    md.push_str("# Prune Refactor Plan\n\n");
    md.push_str(&format!("**Generated:** {}\n", generated_at));
    md.push_str(&format!("**Finding ID:** {}\n", finding.id));
    md.push_str("**Prune Version:** 0.1.0\n\n");

    // Issue section
    md.push_str("## Issue\n\n");
    md.push_str(&format!(
        "**Type:** {}\n",
        finding.pattern_type.display_name()
    ));
    md.push_str(&format!(
        "**Severity:** {}\n",
        capitalize(finding.severity.as_str())
    ));
    md.push_str(&format!(
        "**Confidence:** {:.0}%\n\n",
        finding.confidence * 100.0
    ));
    md.push_str(&format!("{}\n\n", finding.description));

    // Why This Matters section
    if !finding.rationale.is_empty() {
        md.push_str("## Why This Matters\n\n");
        md.push_str(&finding.rationale);
        md.push_str("\n\n");
    }

    // Locations section
    if !finding.locations.is_empty() {
        md.push_str("## Locations\n\n");
        md.push_str("| File | Lines | Context |\n");
        md.push_str("|------|-------|----------|\n");

        for loc in &finding.locations {
            let context = loc.context.as_deref().unwrap_or("-");
            md.push_str(&format!(
                "| `{}` | {}-{} | {} |\n",
                loc.file, loc.start_line, loc.end_line, context
            ));
        }
        md.push('\n');
    }

    // Suggested Approach section
    if !finding.suggested_fix.is_empty() {
        md.push_str("## Suggested Approach\n\n");
        md.push_str(&finding.suggested_fix);
        md.push_str("\n\n");
    }

    // Acceptance Criteria section
    md.push_str("## Acceptance Criteria\n\n");
    md.push_str(&generate_acceptance_criteria(finding));
    md.push('\n');

    // Code Snippets section
    let snippets: Vec<_> = finding
        .locations
        .iter()
        .filter(|l| l.snippet.is_some())
        .collect();

    if !snippets.is_empty() {
        md.push_str("## Relevant Code\n\n");

        for loc in snippets {
            if let Some(snippet) = &loc.snippet {
                md.push_str("<details>\n");
                md.push_str(&format!(
                    "<summary>{}:{}-{}</summary>\n\n",
                    loc.file, loc.start_line, loc.end_line
                ));
                md.push_str("```typescript\n");
                md.push_str(snippet);
                if !snippet.ends_with('\n') {
                    md.push('\n');
                }
                md.push_str("```\n\n");
                md.push_str("</details>\n\n");
            }
        }
    }

    // Verification section
    md.push_str("## Verification\n\n");
    md.push_str("After refactoring, run:\n");
    md.push_str("```bash\n");
    md.push_str(&format!("prune scan --finding {}\n", finding.id));
    md.push_str("```\n\n");
    md.push_str("Expected result: Finding resolved or severity reduced.\n\n");

    // Footer
    md.push_str("---\n");
    md.push_str("*Generated by Prune v0.1.0*\n");

    md
}

fn generate_acceptance_criteria(finding: &Finding) -> String {
    let mut criteria = Vec::new();

    match finding.pattern_type {
        PatternType::InterfaceSprawl => {
            criteria.push("- [ ] Single canonical type definition created".to_string());
            criteria.push("- [ ] All inline type definitions removed or replaced".to_string());
            criteria.push("- [ ] All imports updated to use canonical type".to_string());
            criteria.push("- [ ] No type errors in the codebase".to_string());
        }
        PatternType::RedundantLogic => {
            criteria.push("- [ ] Duplicate logic consolidated into single function".to_string());
            criteria.push("- [ ] All call sites updated to use consolidated function".to_string());
            criteria.push("- [ ] Duplicate functions removed".to_string());
            criteria.push("- [ ] All tests pass".to_string());
        }
        PatternType::GodFile => {
            criteria.push("- [ ] File split into focused modules".to_string());
            criteria.push("- [ ] Each new module has clear responsibility".to_string());
            criteria.push("- [ ] All imports in consuming files updated".to_string());
            criteria.push("- [ ] Export count below threshold".to_string());
        }
        PatternType::BarrelBloat => {
            criteria.push("- [ ] Index file re-exports reduced".to_string());
            criteria.push("- [ ] Direct imports used where appropriate".to_string());
            criteria.push("- [ ] Bundle size reduced (verify with bundler)".to_string());
        }
        PatternType::DeadExports => {
            criteria.push("- [ ] Unused exports removed or made private".to_string());
            criteria.push("- [ ] Intentional public API exports documented".to_string());
            criteria.push("- [ ] No build errors".to_string());
        }
        PatternType::OverAbstraction => {
            criteria.push("- [ ] Unnecessary abstraction layers removed".to_string());
            criteria.push("- [ ] Code still testable (verify test coverage)".to_string());
            criteria.push("- [ ] Call sites simplified".to_string());
        }
        PatternType::ImportCycle => {
            criteria.push("- [ ] Cycle broken by a one-way dependency".to_string());
            criteria
                .push("- [ ] Shared symbols moved to a module both sides can import".to_string());
            criteria.push("- [ ] No remaining import cycle among these files".to_string());
        }
    }

    // Add related concepts if any
    if !finding.related_concepts.is_empty() {
        criteria.push(format!(
            "- [ ] All instances updated: {}",
            finding.related_concepts.join(", ")
        ));
    }

    criteria.join("\n")
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::patterns::{Location, Severity};

    #[test]
    fn test_plan_generation() {
        let finding = Finding::new(
            PatternType::GodFile,
            Severity::High,
            0.95,
            "God file: utils.ts".to_string(),
            "utils.ts has 50 exports".to_string(),
        )
        .with_rationale("Large files are hard to maintain".to_string())
        .with_locations(vec![Location::new("src/utils.ts".to_string(), 1, 500)])
        .with_suggested_fix("Split into smaller modules".to_string());

        let plan = RefactorPlan::generate(&finding);

        assert!(plan.markdown.contains("# Prune Refactor Plan"));
        assert!(plan.markdown.contains("God File"));
        assert!(plan.markdown.contains("utils.ts"));
        assert!(plan.markdown.contains("## Acceptance Criteria"));
    }
}
